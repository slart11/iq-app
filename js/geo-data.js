/**
 * Looks up metadata for a municipality by 4-digit kommunenummer,
 * falling back cleanly if an unknown municipality appears.
 *
 * @param {string | number} id
 * @param {string} [fallbackName]
 * @returns {{ id: string, displayName: string, region: string, fact: string }}
 */
export function getKommuneInfo(id, fallbackName = "") {
  const key = String(id ?? "").trim();
  const entry = KOMMUNE_DATA[key];
  if (entry) {
    return {
      id: key,
      displayName: entry.displayName,
      region: entry.region,
      fact: entry.fact
    };
  }

  const cleanFallback = String(fallbackName ?? "").trim() || "Ukjent kommune";
  return {
    id: key,
    displayName: cleanFallback,
    region: "Trøndelag",
    fact: "Ingen ekstra fakta er registrert for denne kommunen enda."
  };
}
